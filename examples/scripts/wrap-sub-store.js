/*
 * Sub-Store 文件脚本包装器
 *
 * 将文件资源中的 Sub-Store 配置覆写脚本转换为 Sandrone file-stage
 * script。把本脚本配置为源文件的 processor，再将渲染结果用作 script processor
 * 的 file source。
 *
 * 可直接兼容：
 *   - 同步 main(config) 入口；
 *   - $arguments，以及来自请求参数的 $options；
 *   - console 和 $substore 的日志方法；
 *   - yaml.parse/stringify、safeLoad/safeDump、load/dump；
 *   - b64e/b64d、ProxyUtils.Base64 和 ProxyUtils.yaml。
 *
 * console.log/info 会写入 Sandrone 的 api.log；console.warn/error、通知和兼容性
 * 问题会同时生成可见 warning。Sandrone 当前不会在输出或 report 中公开 api.log。
 *
 * 网络、缓存、持久化、lodash、ProxyUtils 节点转换、produceArtifact、Buffer、
 * require 等无等价能力的接口在调用时生成 warning，并保留输入文件。
 *
 * 包装阶段参数（通过本脚本 ProcessorSpec.params.args 传入）：
 *   arguments: object   写入生成脚本的默认 $arguments
 *
 * 生成脚本执行时，input.args 按同名键覆盖默认 $arguments。
 */

var SUBSTORE_WRAPPER_MARKER = "/* Sandrone Sub-Store compatibility wrapper */";

function main(input) {
    input = input || {};
    if (input.stage !== "file" || !input.file || typeof input.file.content !== "string") {
        throw new Error("Sub-Store wrapper requires a file-stage input with text content");
    }
    var source = input.file.content;
    if (!source.trim()) throw new Error("Sub-Store source script must not be empty");
    if (source.indexOf(SUBSTORE_WRAPPER_MARKER) !== -1) return input;

    var args = input.args || {};
    var defaultArguments = args.arguments == null ? {} : args.arguments;
    if (!isPlainObject(defaultArguments)) {
        throw new Error("arguments must be an object");
    }

    input.file.content = buildSandroneWrapper(source, defaultArguments);
    input.file.media_type = "application/javascript";
    input.file.encoding = "utf-8";
    return input;
}

function buildSandroneWrapper(source, defaultArguments) {
    var sections = [
        SUBSTORE_WRAPPER_MARKER,
        "// Generated by https://github.com/kuuvahki-labs/sandrone/blob/main/examples/scripts/wrap-sub-store.js. Do not edit manually.",
        "var __subStoreSource = " + JSON.stringify(source) + ";",
        "var __subStoreDefaultArguments = " + JSON.stringify(defaultArguments) + ";",
        String(__subStoreIsPlainObject),
        String(__subStoreCopyObject),
        String(__subStoreMergeArguments),
        String(__subStoreFormatValues),
        String(__subStoreLog),
        String(__subStoreWarn),
        String(__subStoreConsole),
        String(__subStoreUnsupported),
        String(__subStoreYAML),
        String(__subStoreBase64),
        String(__subStoreProxyUtils),
        String(__subStoreAPI),
        String(__subStoreLoadMain),
        String(__subStoreRun),
        "function main(input, api) { return __subStoreRun(input, api); }",
        "globalThis.main = main;",
        ""
    ];
    return sections.join("\n\n");
}

function isPlainObject(value) {
    if (!value || Object.prototype.toString.call(value) !== "[object Object]") return false;
    var prototype = Object.getPrototypeOf(value);
    return prototype === null || prototype === Object.prototype;
}

/* 以下函数会原样写入生成脚本，因此只能依赖同样以 __subStore 开头的函数。 */

function __subStoreIsPlainObject(value) {
    if (!value || Object.prototype.toString.call(value) !== "[object Object]") return false;
    var prototype = Object.getPrototypeOf(value);
    return prototype === null || prototype === Object.prototype;
}

function __subStoreCopyObject(value) {
    var result = {};
    if (!__subStoreIsPlainObject(value)) return result;
    Object.keys(value).forEach(function(key) {
        result[key] = value[key];
    });
    return result;
}

function __subStoreMergeArguments(defaults, overrides) {
    var result = __subStoreCopyObject(defaults);
    if (!__subStoreIsPlainObject(overrides)) return result;
    Object.keys(overrides).forEach(function(key) {
        result[key] = overrides[key];
    });
    return result;
}

function __subStoreFormatValues(values) {
    return Array.prototype.map.call(values, function(value) {
        if (typeof value === "string") return value;
        try {
            var encoded = JSON.stringify(value);
            if (encoded !== undefined) return encoded;
        } catch (_) {
            // JSON 无法编码时退回普通字符串，避免日志本身中断脚本。
        }
        try {
            return String(value);
        } catch (_) {
            return "[unprintable value]";
        }
    }).join(" ");
}

function __subStoreLog(api, level, values) {
    var message = __subStoreFormatValues(values);
    if (api && typeof api.log === "function") {
        api.log("[Sub-Store " + level + "] " + message);
    }
    return message;
}

function __subStoreWarn(api, code, message) {
    if (api && typeof api.log === "function") {
        api.log("[Sub-Store compatibility] " + message);
    }
    if (api && typeof api.warn === "function") {
        api.warn({code: code, message: message, source: "sub-store"});
    }
}

function __subStoreConsole(api) {
    function log(level, values) {
        return __subStoreLog(api, level, values);
    }
    function visible(level, code, values) {
        var message = log(level, values);
        __subStoreWarn(api, code, "Source script emitted " + level + ": " + message);
    }
    return {
        log: function() { log("LOG", arguments); },
        debug: function() { log("DEBUG", arguments); },
        info: function() { log("INFO", arguments); },
        warn: function() { visible("WARN", "substore_script_warn", arguments); },
        error: function() { visible("ERROR", "substore_script_error", arguments); },
        dir: function() { log("DIR", arguments); },
        trace: function() { log("TRACE", arguments); },
        assert: function(condition) {
            if (!condition) {
                var values = Array.prototype.slice.call(arguments, 1);
                if (values.length === 0) values.push("Assertion failed");
                visible("ASSERT", "substore_script_assert", values);
            }
        }
    };
}

function __subStoreUnsupported(name) {
    function fail() {
        var error = new Error("Sub-Store host capability " + name + " is unavailable in Sandrone");
        error.sandroneSubStoreUnsupported = name;
        throw error;
    }
    if (typeof Proxy !== "function") return fail;
    return new Proxy(fail, {
        get: function(_, property) {
            // 避免 Promise 检测把占位对象当作 thenable。
            if (property === "then") return undefined;
            return __subStoreUnsupported(name + "." + String(property));
        },
        apply: function() { return fail(); },
        construct: function() { return fail(); }
    });
}

function __subStoreYAML(api) {
    var yaml = {
        parse: function(text) { return api.yaml.parse(text); },
        load: function(text) { return api.yaml.parse(text); },
        safeLoad: function(text) { return api.yaml.parse(text); },
        stringify: function(value) { return api.yaml.stringify(value); },
        dump: function(value) { return api.yaml.stringify(value); },
        safeDump: function(value) { return api.yaml.stringify(value); }
    };
    if (typeof Proxy !== "function") return yaml;
    return new Proxy(yaml, {
        get: function(target, property) {
            if (property in target) return target[property];
            return __subStoreUnsupported("yaml." + String(property));
        }
    });
}

function __subStoreBase64(api) {
    var base64 = {
        encode: function(text) { return api.base64.encode(text); },
        decode: function(text) { return api.base64.decode(text); },
        btoa: function(text) { return api.base64.encode(text); },
        atob: function(text) { return api.base64.decode(text); }
    };
    if (typeof Proxy !== "function") return base64;
    return new Proxy(base64, {
        get: function(target, property) {
            if (property in target) return target[property];
            return __subStoreUnsupported("ProxyUtils.Base64." + String(property));
        }
    });
}

function __subStoreProxyUtils(yaml, base64) {
    var proxyUtils = {yaml: yaml, Base64: base64};
    if (typeof Proxy !== "function") return proxyUtils;
    return new Proxy(proxyUtils, {
        get: function(target, property) {
            if (property in target) return target[property];
            return __subStoreUnsupported("ProxyUtils." + String(property));
        }
    });
}

function __subStoreAPI(api, consoleAPI) {
    var substore = {
        env: {
            isQX: false,
            isLoon: false,
            isSurge: false,
            isNode: false,
            isStash: false,
            isShadowRocket: false,
            isEgern: false,
            isLanceX: false,
            isGUIforCores: false,
            isSandrone: true
        },
        log: function() { consoleAPI.log.apply(consoleAPI, arguments); },
        info: function() { consoleAPI.info.apply(consoleAPI, arguments); },
        warn: function() { consoleAPI.warn.apply(consoleAPI, arguments); },
        error: function() { consoleAPI.error.apply(consoleAPI, arguments); },
        notify: function() {
            var message = __subStoreFormatValues(arguments);
            __subStoreWarn(api, "substore_notification", "Source script requested a notification: " + message);
        },
        done: function() {
            __subStoreLog(api, "DONE", ["Ignored $substore.done(); Sandrone completes through the entrypoint return value"]);
        },
        http: __subStoreUnsupported("$substore.http"),
        wait: __subStoreUnsupported("$substore.wait"),
        read: __subStoreUnsupported("$substore.read"),
        write: __subStoreUnsupported("$substore.write"),
        delete: __subStoreUnsupported("$substore.delete"),
        cache: __subStoreUnsupported("$substore.cache"),
        node: __subStoreUnsupported("$substore.node")
    };
    if (typeof Proxy !== "function") return substore;
    return new Proxy(substore, {
        get: function(target, property) {
            if (property in target) return target[property];
            return __subStoreUnsupported("$substore." + String(property));
        }
    });
}

function __subStoreLoadMain(source, host) {
    var globalObject = globalThis;
    var hadGlobalMain = Object.prototype.hasOwnProperty.call(globalObject, "main");
    var previousGlobalMain = globalObject.main;
    var loaded;
    try {
        loaded = (function(
            $arguments,
            $options,
            $substore,
            lodash,
            ProxyUtils,
            yaml,
            Buffer,
            b64d,
            b64e,
            DOMAIN_RESOLVERS,
            scriptResourceCache,
            flowUtils,
            produceArtifact,
            require,
            console
        ) {
            return eval(source + "\n;typeof main === 'function' ? main : undefined;");
        })(
            host.arguments,
            host.options,
            host.substore,
            host.lodash,
            host.proxyUtils,
            host.yaml,
            host.buffer,
            host.b64d,
            host.b64e,
            host.domainResolvers,
            host.scriptResourceCache,
            host.flowUtils,
            host.produceArtifact,
            host.require,
            host.console
        );
        if (typeof loaded !== "function" && typeof globalObject.main === "function") {
            loaded = globalObject.main;
        }
    } finally {
        if (hadGlobalMain) globalObject.main = previousGlobalMain;
        else delete globalObject.main;
    }
    if (typeof loaded !== "function") {
        throw new Error("Sub-Store script does not define a callable main(config) entrypoint");
    }
    return loaded;
}

function __subStoreRun(input, api) {
    input = input || {};
    if (input.stage !== "file" || !input.file || typeof input.file.content !== "string") {
        throw new Error("Generated Sub-Store wrapper requires a file-stage input with text content");
    }
    if (!api || !api.yaml || !api.base64) {
        throw new Error("Current Sandrone runtime does not provide the YAML or Base64 API");
    }

    var config = api.yaml.parse(input.file.content);
    if (!__subStoreIsPlainObject(config)) {
        throw new Error("Configuration document root must be an object");
    }

    var scriptArguments = __subStoreMergeArguments(
        __subStoreDefaultArguments,
        input.args
    );
    var requestArguments = input.request && input.request.args;
    var scriptOptions = __subStoreCopyObject(requestArguments);
    var consoleAPI = __subStoreConsole(api);
    var yaml = __subStoreYAML(api);
    var base64 = __subStoreBase64(api);
    var unsupported = __subStoreUnsupported;
    var host = {
        arguments: scriptArguments,
        options: scriptOptions,
        console: consoleAPI,
        substore: __subStoreAPI(api, consoleAPI),
        yaml: yaml,
        proxyUtils: __subStoreProxyUtils(yaml, base64),
        b64d: base64.decode,
        b64e: base64.encode,
        lodash: unsupported("lodash"),
        buffer: unsupported("Buffer"),
        domainResolvers: unsupported("DOMAIN_RESOLVERS"),
        scriptResourceCache: unsupported("scriptResourceCache"),
        flowUtils: unsupported("flowUtils"),
        produceArtifact: unsupported("produceArtifact"),
        require: unsupported("require")
    };

    var result;
    try {
        var subStoreMain = __subStoreLoadMain(__subStoreSource, host);
        result = subStoreMain(config);
    } catch (error) {
        if (error && error.sandroneSubStoreUnsupported) {
            __subStoreWarn(
                api,
                "substore_host_unsupported",
                "Source script called unsupported host capability " +
                    error.sandroneSubStoreUnsupported +
                    "; changes were skipped and the original configuration was preserved"
            );
            return input;
        }
        throw error;
    }

    if (result && typeof result.then === "function") {
        __subStoreWarn(
            api,
            "substore_async_unsupported",
            "Source script returned a Promise; Sandrone entrypoints are synchronous, so the original configuration was preserved"
        );
        return input;
    }
    if (!__subStoreIsPlainObject(result)) {
        throw new Error("Sub-Store main(config) must synchronously return a configuration object");
    }
    if (scriptOptions._res !== undefined) {
        __subStoreWarn(
            api,
            "substore_response_unsupported",
            "Source script set $options._res; Sandrone file processors cannot change HTTP response properties, so it was ignored"
        );
    }

    input.file.content = api.yaml.stringify(result);
    return input;
}
